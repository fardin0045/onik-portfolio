const normalise = (name = '') =>
  name
    .toLowerCase()
    .replace(/\(.*?\)/g, '')
    .replace(/\.js\b|\.(?=\w)/g, (m) => (m === '.js' ? 'js' : ''))
    .replace(/[^a-z0-9#+&/ ]/g, '')
    .replace(/\s+/g, ' ')
    .trim();

/** Returns { Icon, color } for a technology name, or null when unknown. */
export function techIcon(name) {
  const key = normalise(name);
  return REGISTRY[key] || REGISTRY[key.replace(/ /g, '')] || REGISTRY[key.replace(/js$/, '').trim()] || null;
}
